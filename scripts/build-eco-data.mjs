#!/usr/bin/env node
// One-shot generator for src/chess/ecoOpenings.ts.
//
// Sources:
//   scripts/eco-tsv/{a,b,c,d,e}.tsv — copies of
//   https://github.com/lichess-org/chess-openings (CC0, public domain).
//
// For each ECO code we pick the entry with the shortest PGN line as the
// canonical name (this is the "root" of the family for that code). ECO codes
// where many unrelated openings share the bucket — A00 is the big one — are
// skipped; the helper falls back to the ECO family name in that case.
//
// To regenerate: refresh the TSVs in scripts/eco-tsv/ and run
//   node scripts/build-eco-data.mjs
// The output replaces src/chess/ecoOpenings.ts.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const tsvDir = join(here, 'eco-tsv');
const outPath = join(here, '..', 'src', 'chess', 'ecoOpenings.ts');

// ECO codes whose entries are too heterogeneous to name canonically.
const SKIP_ECO = new Set(['A00']);

const best = new Map(); // eco -> { name, pgnLen }

for (const letter of ['a', 'b', 'c', 'd', 'e']) {
  const tsv = readFileSync(join(tsvDir, `${letter}.tsv`), 'utf8');
  const lines = tsv.split('\n');
  for (let i = 1; i < lines.length; i++) {
    const line = lines[i];
    if (!line) continue;
    const [eco, name, pgn] = line.split('\t');
    if (!eco || !name || !pgn) continue;
    if (SKIP_ECO.has(eco)) continue;
    const len = pgn.length;
    const cur = best.get(eco);
    if (!cur || len < cur.pgnLen) {
      best.set(eco, { name, pgnLen: len });
    }
  }
}

const sortedEcos = [...best.keys()].sort();


function quote(s) {
  // Use double quotes; escape backslashes and double quotes.
  return `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

let out = `// Auto-generated by scripts/build-eco-data.mjs. Do not edit by hand.
// Source: https://github.com/lichess-org/chess-openings (CC0).

export const ECO_OPENING_NAMES: Record<string, string> = {
`;
for (const eco of sortedEcos) {
  out += `  ${quote(eco)}: ${quote(best.get(eco).name)},\n`;
}
out += `};\n`;

writeFileSync(outPath, out);
console.log(`Wrote ${sortedEcos.length} ECO entries to ${outPath}`);
